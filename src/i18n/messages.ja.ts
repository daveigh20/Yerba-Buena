const JA_FIELD_NAMES: Record<string, string> = {
  age: "年齢",
  "weight in kg": "体重（kg）",
  "height in cm": "身長（cm）",
};

function translateErrorJa(message: string): string | undefined {
  if (JA_ERRORS[message]) return JA_ERRORS[message];
  let m = /^Password must be at (least|most) (\d+) characters\.$/.exec(message);
  if (m) return `パスワードは${m[2]}文字${m[1] === "least" ? "以上" : "以内"}にしてください。`;
  m = /^Please enter your (.+)\.$/.exec(message);
  if (m && JA_FIELD_NAMES[m[1]!]) return `${JA_FIELD_NAMES[m[1]!]}を入力してください。`;
  m = /^Please enter a valid (.+) \((\d+)–(\d+)\)\.$/.exec(message);
  if (m && JA_FIELD_NAMES[m[1]!]) return `有効な${JA_FIELD_NAMES[m[1]!]}を入力してください（${m[2]}–${m[3]}）。`;
  m = /^Request failed \((\d+)\)\.$/.exec(message);
  if (m) return `リクエストに失敗しました（${m[1]}）。`;
  return undefined;
}

