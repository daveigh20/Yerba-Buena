/** Each field as "your X" and as "a valid X", so articles and adjectives agree in gender. */
const ES_FIELD_NAMES: Record<string, { yours: string; valid: string }> = {
  age: { yours: "tu edad", valid: "una edad válida" },
  "weight in kg": { yours: "tu peso en kg", valid: "un peso válido en kg" },
  "height in cm": { yours: "tu estatura en cm", valid: "una estatura válida en cm" },
};

function translateErrorEs(message: string): string | undefined {
  if (ES_ERRORS[message]) return ES_ERRORS[message];
  let m = /^Password must be at (least|most) (\d+) characters\.$/.exec(message);
  if (m) return `La contraseña debe tener ${m[1] === "least" ? "al menos" : "como máximo"} ${m[2]} caracteres.`;
  m = /^Please enter your (.+)\.$/.exec(message);
  if (m && ES_FIELD_NAMES[m[1]!]) return `Escribe ${ES_FIELD_NAMES[m[1]!]!.yours}.`;
  m = /^Please enter a valid (.+) \((\d+)–(\d+)\)\.$/.exec(message);
  if (m && ES_FIELD_NAMES[m[1]!]) return `Escribe ${ES_FIELD_NAMES[m[1]!]!.valid} (${m[2]}–${m[3]}).`;
  m = /^Request failed \((\d+)\)\.$/.exec(message);
  if (m) return `La solicitud falló (${m[1]}).`;
  return undefined;
}

