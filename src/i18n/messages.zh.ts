function translateErrorZh(message: string): string | undefined {
  if (ZH_ERRORS[message]) return ZH_ERRORS[message];
  let m = /^Password must be at (least|most) (\d+) characters\.$/.exec(message);
  if (m) return `密码${m[1] === "least" ? "至少" : "最多"} ${m[2]} 个字符。`;
  m = /^Please enter your (.+)\.$/.exec(message);
  if (m && ZH_FIELD_NAMES[m[1]!]) return `请输入你的${ZH_FIELD_NAMES[m[1]!]}。`;
  m = /^Please enter a valid (.+) \((\d+)–(\d+)\)\.$/.exec(message);
  if (m && ZH_FIELD_NAMES[m[1]!]) return `请输入有效的${ZH_FIELD_NAMES[m[1]!]}（${m[2]}–${m[3]}）。`;
  m = /^Request failed \((\d+)\)\.$/.exec(message);
  if (m) return `请求失败（${m[1]}）。`;
  return undefined;
}

